from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .fixtures import (
    FixtureTree,
    inspect_fixture_tree,
    meaningful_file_count,
    verify_fixture_tree,
)

ROOT = Path(__file__).resolve().parents[2]
BENCHMARK_ROOT = ROOT / "benchmarks"
AREAS_PATH = BENCHMARK_ROOT / "fixture-areas.json"
AUDIT_PATH = BENCHMARK_ROOT / "fixture-audit.md"
INVENTORY_ROOT = BENCHMARK_ROOT / "inventories"
MANIFEST_ROOT = BENCHMARK_ROOT / "manifests"


def _declared_tree(root: Path) -> FixtureTree:
    manifest_path = MANIFEST_ROOT / f"{root.name}.json"
    inventory_path = INVENTORY_ROOT / f"{root.name}.json"
    if manifest_path.is_file():
        data = json.loads(manifest_path.read_text(encoding="utf-8"))["repository"]
        tree = FixtureTree.from_mapping(data, source=str(manifest_path))
    elif inventory_path.is_file():
        data = json.loads(inventory_path.read_text(encoding="utf-8"))
        tree = FixtureTree.from_mapping(data, source=str(inventory_path))
    else:
        return inspect_fixture_tree(root, allow_empty=True)
    verify_fixture_tree(root, tree)
    return tree


def _counts(root: Path) -> tuple[int, int]:
    tree = _declared_tree(root)
    return meaningful_file_count(root, tree), len(tree.files)


def build_entries() -> list[dict[str, Any]]:
    areas = json.loads(AREAS_PATH.read_text(encoding="utf-8"))
    entries: list[dict[str, Any]] = []
    for area in areas:
        root = ROOT / area["path"]
        included = set(area.get("fixtures", []))
        fixtures = [
            path
            for path in root.iterdir()
            if path.is_dir() and (not included or path.name in included)
        ]
        for fixture in sorted(fixtures):
            meaningful, total = _counts(fixture)
            entries.append(
                {
                    **{
                        key: value
                        for key, value in area.items()
                        if key not in {"path", "fixtures"}
                    },
                    "fixture_id": fixture.name,
                    "path": fixture.relative_to(ROOT).as_posix(),
                    "meaningful_files": meaningful,
                    "total_files": total,
                }
            )
    return entries


def render_audit() -> str:
    lines = [
        "# Fixture Audit",
        "",
        "Generated by `python -m tools.benchmarks audit`. Counts use canonical fixture "
        "inventories where available and centrally exclude runtime caches. The meaningful "
        "count also excludes empty package markers, generated SDK output, and the legacy "
        "numbered scale pattern.",
        "",
        "## Initial repository evidence",
        "",
        "- The worktree was clean at `50f33bb`; pytest collected 453 tests.",
        "- Plan and implementation evaluation repositories contain at most 9 and 5 files; "
        "audit has 18- and 8-file cases; optimize cases contain 1-4 files.",
        "- `design-codebase` has no tracked evaluation portfolio.",
        "- The initial `realistic-large` worktree observation counted 228 files because it "
        "included ten ignored `.ruff_cache` artifacts. Its canonical source-controlled tree "
        "has 218 files, including 206 mechanically numbered files, and is homogeneous stress "
        "coverage rather than realistic utility evidence.",
        "- Plan and audit scoring relies materially on keywords. Audit fixture tests were "
        "previously collected as ordinary repository tests and are now explicitly ignored.",
        "- No pytest benchmark markers existed initially. The full Windows suite did not "
        "complete within a bounded 180-second exploratory run.",
        "",
        "## Fixture catalog",
        "",
        "| Skill | Fixture | Tier | Classification | Domain | Languages | Meaningful | Total | Task / oracle | Baseline | CI command | Limitation |",
        "| --- | --- | --- | --- | --- | --- | ---: | ---: | --- | --- | --- | --- |",
    ]
    for entry in build_entries():
        lines.append(
            "| {skill} | `{fixture_id}` | {tier} | {classification} | {domain} | {languages} | "
            "{meaningful_files} | {total_files} | {task_oracle} | {baseline} | `{ci_command}` | "
            "{limitation} |".format(**entry)
        )
    return "\n".join(lines) + "\n"
